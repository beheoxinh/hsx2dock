/**
 * Unit tests for template rendering, password generation and name helpers.
 * Run with: node --test src/lib/composeTemplates.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import {
  COMPOSE_TEMPLATES,
  defaultProjectDir,
  formatEnvFile,
  generatePassword,
  PASSWORD_ALPHABET,
  slugProjectName,
  templateSecrets,
} from "./composeTemplates.ts";

test("every template declares every secret it references in its YAML", () => {
  for (const t of COMPOSE_TEMPLATES) {
    const refs = [...t.yaml.matchAll(/\$\{([A-Z_][A-Z0-9_]*)\}/g)].map((m) => m[1]);
    for (const ref of refs) {
      assert.ok(t.secrets.includes(ref), `${t.id} references ${ref} but does not generate it`);
    }
  }
});

test("template ids are unique and YAML starts with services", () => {
  const ids = COMPOSE_TEMPLATES.map((t) => t.id);
  assert.equal(new Set(ids).size, ids.length);
  for (const t of COMPOSE_TEMPLATES) assert.match(t.yaml, /^services:\n/);
});

test("password has the requested length and only alphabet characters", () => {
  const pw = generatePassword(32);
  assert.equal(pw.length, 32);
  for (const ch of pw) assert.ok(PASSWORD_ALPHABET.includes(ch), `unexpected ${ch}`);
});

test("password generation rejects biased bytes instead of wrapping them", () => {
  // 248 is the first byte past the unbiased range (62 * 4): it must be skipped.
  const feed = [248, 255, 0, 61, 62];
  let i = 0;
  const pw = generatePassword(3, () => Uint8Array.from(feed.slice(i, (i += 5))));
  assert.equal(pw, PASSWORD_ALPHABET[0] + PASSWORD_ALPHABET[61] + PASSWORD_ALPHABET[0]);
});

test("generated secrets cover exactly the template's keys", () => {
  const t = COMPOSE_TEMPLATES.find((x) => x.id === "wordpress-mariadb")!;
  const values = templateSecrets(t, () => "x");
  assert.deepEqual(Object.keys(values).sort(), ["MARIADB_PASSWORD", "MARIADB_ROOT_PASSWORD"]);
});

test("env file lists KEY=value lines under a header", () => {
  const text = formatEnvFile({ A: "1", B: "two" });
  assert.match(text, /^# Generated by hsx2dock/);
  assert.match(text, /\nA=1\nB=two\n$/);
  assert.equal(formatEnvFile({}), "");
});

test("project names are slugged to compose's rules", () => {
  assert.equal(slugProjectName("  My Shop!  "), "my-shop");
  assert.equal(slugProjectName("--_web_--"), "web_");
  assert.equal(slugProjectName("!!!"), "app");
});

test("default folder lives under ~/compose", () => {
  assert.equal(defaultProjectDir("Blog App"), "~/compose/blog-app");
});
